//! A synthetic repository for the benchmarks: 10,000 source files, the same bytes on every run.
//!
//! A hundred folders of a hundred files each; even folders hold Python, odd ones TypeScript. Each
//! file defines a class and eight functions, about 70 lines, and imports names from two files of
//! its own language in other folders, so that imports resolve and names tie across files. That
//! makes about 700,000 lines: a medium repository, below the million lines that make one huge.

use std::fmt::Write as _;
use std::io;
use std::path::{Path, PathBuf};

/// Folders in the repository.
const FOLDERS: usize = 100;

/// Files in each folder.
const FILES_PER_FOLDER: usize = 100;

/// Functions each file defines besides its class.
const FUNCTIONS_PER_FILE: usize = 8;

/// Bumped whenever the generated bytes change, so that a stale copy is not reused.
const GENERATOR_VERSION: u32 = 1;

/// The file written last, whose presence says the repository is complete.
const COMPLETE_MARK: &str = "generated.txt";

/// The synthetic repository's root, generated when missing. It lives in the system's temporary
/// folder, outside any repository, and is reused by later runs.
///
/// # Errors
///
/// I/O errors while writing it.
pub fn repository() -> io::Result<PathBuf> {
    let root = std::env::temp_dir()
        .join("cortex-bench")
        .join(format!("synthetic-10k-v{GENERATOR_VERSION}"));
    if root.join(COMPLETE_MARK).exists() {
        return Ok(root);
    }
    for folder in 0..FOLDERS {
        let folder_path = root.join(format!("pkg{folder:02}"));
        std::fs::create_dir_all(&folder_path)?;
        for file in 0..FILES_PER_FOLDER {
            let (name, source) = module(folder, file);
            std::fs::write(folder_path.join(name), source)?;
        }
    }
    std::fs::write(root.join(COMPLETE_MARK), "complete\n")?;
    Ok(root)
}

/// The repository-relative path of the file the reparse benchmark changes.
pub const CHANGED_FILE: &str = "pkg00/m000.py";

/// Writes variant `variant` of [`CHANGED_FILE`] into the repository at `root`: its own source
/// with one more function whose body depends on the variant, so that each variant differs from
/// the last.
///
/// # Errors
///
/// I/O errors.
pub fn change_file(root: &Path, variant: u64) -> io::Result<()> {
    let (_, mut source) = module(0, 0);
    let _ = write!(
        source,
        "\n\ndef changed_{variant}(value):\n    return value + {variant}\n"
    );
    std::fs::write(root.join(CHANGED_FILE), source)
}

/// The file name and source of file `file` of folder `folder`.
fn module(folder: usize, file: usize) -> (String, String) {
    // Imported files: two folders on, of the same language, at spread-out positions.
    let first = ((folder + 2) % FOLDERS, (file * 7 + 3) % FILES_PER_FOLDER);
    let second = ((folder + 4) % FOLDERS, (file * 13 + 5) % FILES_PER_FOLDER);
    if folder.is_multiple_of(2) {
        (
            format!("m{file:03}.py"),
            python(folder, file, first, second),
        )
    } else {
        (
            format!("m{file:03}.ts"),
            typescript(folder, file, first, second),
        )
    }
}

/// A Python module that imports from the files `first` and `second`.
fn python(folder: usize, file: usize, first: (usize, usize), second: (usize, usize)) -> String {
    let id = |(f, n): (usize, usize)| format!("{f}_{n}");
    let (me, one, two) = (id((folder, file)), id(first), id(second));
    let mut source = format!(
        "\"\"\"Module {me}.\"\"\"\n\
         from pkg{:02}.m{:03} import helper_{one}_0, Model_{one}\n\
         from pkg{:02}.m{:03} import helper_{two}_1\n\n\
         LIMIT_{me} = {file}\n\n\n\
         class Model_{me}:\n    \"\"\"A model.\"\"\"\n\n\
         \x20   def __init__(self, value):\n        self.value = value\n        self.items = []\n\n\
         \x20   def add(self, item):\n        if item is None:\n            return False\n\
         \x20       self.items.append(item)\n        return True\n\n\
         \x20   def total(self):\n        result = 0\n        for item in self.items:\n\
         \x20           result += helper_{one}_0(item)\n        return result\n",
        first.0, first.1, second.0, second.1
    );
    for function in 0..FUNCTIONS_PER_FILE {
        let _ = write!(
            source,
            "\n\ndef helper_{me}_{function}(value):\n    \"\"\"Step {function}.\"\"\"\n\
             \x20   if value > LIMIT_{me}:\n        return helper_{two}_1(value)\n\
             \x20   model = Model_{one}(value)\n    model.add(value)\n    return model.total()\n"
        );
    }
    source
}

/// A TypeScript module that imports from the files `first` and `second`.
fn typescript(folder: usize, file: usize, first: (usize, usize), second: (usize, usize)) -> String {
    let id = |(f, n): (usize, usize)| format!("{f}_{n}");
    let (me, one, two) = (id((folder, file)), id(first), id(second));
    let mut source = format!(
        "// Module {me}.\n\
         import {{ helper_{one}_0, Model_{one} }} from \"../pkg{:02}/m{:03}\";\n\
         import {{ helper_{two}_1 }} from \"../pkg{:02}/m{:03}\";\n\n\
         export const LIMIT_{me} = {file};\n\n\
         export class Model_{me} {{\n  items: number[] = [];\n\n\
         \x20 constructor(public value: number) {{}}\n\n\
         \x20 add(item: number | undefined): boolean {{\n    if (item === undefined) {{\n\
         \x20     return false;\n    }}\n    this.items.push(item);\n    return true;\n  }}\n\n\
         \x20 total(): number {{\n    let result = 0;\n    for (const item of this.items) {{\n\
         \x20     result += helper_{one}_0(item);\n    }}\n    return result;\n  }}\n}}\n",
        first.0, first.1, second.0, second.1
    );
    for function in 0..FUNCTIONS_PER_FILE {
        let _ = write!(
            source,
            "\n/** Step {function}. */\nexport function helper_{me}_{function}(value: number): number {{\n\
             \x20 if (value > LIMIT_{me}) {{\n    return helper_{two}_1(value);\n  }}\n\
             \x20 const model = new Model_{one}(value);\n  model.add(value);\n  return model.total();\n}}\n"
        );
    }
    source
}
