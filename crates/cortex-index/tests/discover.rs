//! Discovery on real folder trees: what the walk leaves out, the flags each file gets, files it
//! must never open, and the problems it reports.

mod common;

use std::fs::{self, File};
use std::path::Path;
use std::time::{Duration, UNIX_EPOCH};

use common::{TestResult, lock_out, write};
use cortex_core::{FileFlags, Language, RepoPath};
use cortex_index::{
    DiscoverError, DiscoverOptions, DiscoveredFile, Discovery, Problem, ProblemKind, discover,
};

/// The default size limit, 1 MiB.
const MAX_FILE_BYTES: u64 = 1_048_576;

/// Discovers `root` with no extra patterns and no global gitignore.
fn discover_plain(root: &Path, max_file_bytes: u64) -> Result<Discovery, DiscoverError> {
    discover(
        root,
        &DiscoverOptions {
            max_file_bytes,
            extra_ignores: &[],
            global_gitignore: None,
        },
    )
}

/// The paths of the files found, in order.
fn paths(discovery: &Discovery) -> Vec<&str> {
    discovery
        .files
        .iter()
        .map(|file| file.path.as_str())
        .collect()
}

/// The paths and flags of the files found, in order.
fn flags(discovery: &Discovery) -> Vec<(&str, FileFlags)> {
    discovery
        .files
        .iter()
        .map(|file| (file.path.as_str(), file.flags))
        .collect()
}

/// A problem with the file at `path`.
fn problem(path: &str, kind: ProblemKind) -> TestResult<Problem> {
    Ok(Problem {
        path: Some(RepoPath::new(path)?),
        kind,
    })
}

/// Every ignore source is honoured: `.gitignore` files at the root and below, `.git/info/exclude`,
/// `.cortexignore`, the global gitignore (whose patterns are relative to the repository root) and
/// the extra patterns. Hidden files are kept; `.git` and `.cortex` are never entered. Paths come
/// back sorted as text, which is not the walk's order: the walk lists `a/b.rs` before `a.rs`.
#[test]
fn the_walk_honours_every_ignore_source() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let elsewhere = tempfile::tempdir()?;
    let global = elsewhere.path().join("ignore");
    fs::write(&global, "*.swp\n/top.txt\nsub/x.txt\n")?;
    write(root, ".gitignore", b"*.tmp\nbuild-output/\n")?;
    write(root, ".cortexignore", b"docs/private/\n")?;
    write(root, ".git/info/exclude", b"local.txt\n")?;
    write(root, ".git/config", b"[core]\n")?;
    write(root, ".cortex/cortex.db", b"")?;
    write(root, "sub/.gitignore", b"*.gen.rs\n")?;
    for path in [
        "a.rs",
        "a/b.rs",
        "src/main.rs",
        "src/a.tmp",
        "build-output/x.js",
        "docs/private/notes.md",
        "docs/readme.md",
        "local.txt",
        "sub/x.gen.rs",
        "sub/y.rs",
        "sub/x.txt",
        "scratch/z.rs",
        ".hidden/config.yml",
        "edit.swp",
        "top.txt",
        "deep/top.txt",
    ] {
        write(root, path, b"text\n")?;
    }
    let extra = vec!["scratch/".to_owned()];
    let discovery = discover(
        root,
        &DiscoverOptions {
            max_file_bytes: MAX_FILE_BYTES,
            extra_ignores: &extra,
            global_gitignore: Some(&global),
        },
    )?;
    assert_eq!(
        paths(&discovery),
        [
            ".cortexignore",
            ".gitignore",
            ".hidden/config.yml",
            "a.rs",
            "a/b.rs",
            "deep/top.txt",
            "docs/readme.md",
            "src/main.rs",
            "sub/.gitignore",
            "sub/y.rs",
        ]
    );
    assert_eq!(discovery.problems, []);
    assert_eq!(discovery.skipped_entries, 0);
    Ok(())
}

/// Each file gets the flags its path, size, first bytes and attributes earn, with its size and
/// modification time. The attributes override the path rules both ways.
#[test]
fn files_get_their_flags() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(root, ".env", b"KEY=1\n")?;
    write(root, "big.txt", &[b'x'; 2000])?;
    write(root, "image.png", b"PNG\0\x01")?;
    write(
        root,
        "gen/api.pb.go",
        b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
    )?;
    write(root, "node_modules/lib/index.js", b"module.exports = 1;\n")?;
    write(root, "dist/app.min.js", b"x=1\n")?;
    write(root, "src/lib.rs", b"pub fn f() {}\n")?;
    write(root, "src/schema.rs", b"pub struct S;\n")?;
    write(root, "vendor/x.go", b"package x\n")?;
    write(
        root,
        ".gitattributes",
        b"src/schema.rs linguist-generated\ndist/** -linguist-generated\nvendor/** -linguist-vendored\n",
    )?;
    let modified = UNIX_EPOCH + Duration::from_secs(1_700_000_000);
    File::options()
        .write(true)
        .open(root.join("src/lib.rs"))?
        .set_modified(modified)?;
    let discovery = discover_plain(root, 1000)?;
    assert_eq!(
        flags(&discovery),
        [
            (".env", FileFlags::SECRET_PATTERN),
            (".gitattributes", FileFlags::empty()),
            ("big.txt", FileFlags::TOO_LARGE),
            ("dist/app.min.js", FileFlags::empty()),
            ("gen/api.pb.go", FileFlags::GENERATED),
            ("image.png", FileFlags::BINARY),
            ("node_modules/lib/index.js", FileFlags::VENDORED),
            ("src/lib.rs", FileFlags::empty()),
            ("src/schema.rs", FileFlags::GENERATED),
            ("vendor/x.go", FileFlags::empty()),
        ]
    );
    let lib = discovery
        .files
        .iter()
        .find(|file| file.path.as_str() == "src/lib.rs")
        .ok_or("src/lib.rs missing")?;
    assert_eq!(
        lib,
        &DiscoveredFile {
            path: RepoPath::new("src/lib.rs")?,
            language: Some(Language::Rust),
            size_bytes: 14,
            mtime_ns: 1_700_000_000_000_000_000,
            flags: FileFlags::empty(),
        }
    );
    assert_eq!(discovery.problems, []);
    Ok(())
}

/// Attribute files follow git's precedence: a deeper `.gitattributes` wins over a shallower one,
/// `.git/info/attributes` over both, and a pattern with a slash is anchored to its file's folder.
#[test]
fn attributes_follow_git_precedence() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(root, ".gitattributes", b"*.js linguist-generated\n")?;
    write(
        root,
        "web/.gitattributes",
        b"*.js -linguist-generated\nlib/*.js linguist-vendored\n",
    )?;
    write(
        root,
        ".git/info/attributes",
        b"web/app.js linguist-generated\n",
    )?;
    for path in [
        "app.js",
        "web/app.js",
        "web/other.js",
        "web/lib/x.js",
        "lib/x.js",
    ] {
        write(root, path, b"x\n")?;
    }
    let generated = FileFlags::GENERATED;
    let discovery = discover_plain(root, MAX_FILE_BYTES)?;
    assert_eq!(
        flags(&discovery),
        [
            (".gitattributes", FileFlags::empty()),
            ("app.js", generated),
            ("lib/x.js", generated),
            ("web/.gitattributes", FileFlags::empty()),
            ("web/app.js", generated),
            ("web/lib/x.js", FileFlags::VENDORED),
            ("web/other.js", FileFlags::empty()),
        ]
    );
    Ok(())
}

/// Each file gets its language from its name, its extension or its `#!` line, a `.h` header from
/// what it holds, and `linguist-language` overrides them all, also to a language Cortex does not
/// parse. Files whose start is never read still get a language from their name.
#[test]
fn languages_are_detected() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(
        root,
        ".gitattributes",
        b"legacy/*.py linguist-language=Text\n",
    )?;
    write(root, "src/app.ts", b"export const a = 1;\n")?;
    write(
        root,
        "include/widget.h",
        b"namespace ui {\nclass Widget;\n}\n",
    )?;
    write(root, "include/add.h", b"int add(int a, int b);\n")?;
    write(root, "bin/tool", b"#!/usr/bin/env python3\nprint(1)\n")?;
    write(root, "legacy/old.py", b"print(2)\n")?;
    write(root, "notes.txt", b"plain\n")?;
    write(root, "big.json", &[b' '; 300])?;
    let discovery = discover_plain(root, 200)?;
    let languages: Vec<(&str, Option<Language>)> = discovery
        .files
        .iter()
        .map(|file| (file.path.as_str(), file.language))
        .collect();
    assert_eq!(
        languages,
        [
            (".gitattributes", None),
            ("big.json", Some(Language::Json)),
            ("bin/tool", Some(Language::Python)),
            ("include/add.h", Some(Language::C)),
            ("include/widget.h", Some(Language::Cpp)),
            ("legacy/old.py", None),
            ("notes.txt", None),
            ("src/app.ts", Some(Language::TypeScript)),
        ]
    );
    Ok(())
}

/// Files that may hold secrets, by their own name or a folder's, rules files inside such folders,
/// and files over the size limit are recorded without being opened. The secret files are under the
/// size limit, so only their names keep them closed. Locked-out ordinary files show the lock works:
/// discovery reports each as unreadable, once, and leaves it out.
#[test]
fn secrets_and_large_files_are_never_opened() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let small = [
        ".env.local",
        "certs/server.pem",
        "config/credentials/aws.json",
        "config/credentials/.gitignore",
        "config/credentials/.gitattributes",
        "notes/locked.txt",
        "notes/.gitignore",
    ];
    for path in small {
        write(root, path, &[b'x'; 100])?;
    }
    write(root, "big.txt", &[b'x'; 300])?;
    let _guards = small
        .iter()
        .chain(["big.txt"].iter())
        .map(|path| lock_out(&root.join(path)))
        .collect::<std::io::Result<Vec<_>>>()?;
    let discovery = discover_plain(root, 200)?;
    assert_eq!(
        discovery.problems,
        [
            problem("notes/.gitignore", ProblemKind::Unreadable)?,
            problem("notes/locked.txt", ProblemKind::Unreadable)?,
        ]
    );
    let secret = FileFlags::SECRET_PATTERN;
    assert_eq!(
        flags(&discovery),
        [
            (".env.local", secret),
            ("big.txt", FileFlags::TOO_LARGE),
            ("certs/server.pem", secret),
            ("config/credentials/.gitattributes", secret),
            ("config/credentials/.gitignore", secret),
            ("config/credentials/aws.json", secret),
        ]
    );
    Ok(())
}

/// A byte order mark before the first line of a rules file is dropped, as git drops it, and
/// braces are literal, as git has no alternation.
#[test]
fn byte_order_marks_and_braces_read_as_git_reads_them() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(root, ".gitignore", b"\xEF\xBB\xBFbom.txt\n{a,b}.tmp\n")?;
    write(
        root,
        ".gitattributes",
        b"\xEF\xBB\xBF*.c linguist-generated\n",
    )?;
    for path in ["bom.txt", "{a,b}.tmp", "a.tmp", "b.tmp", "x.c"] {
        write(root, path, b"x\n")?;
    }
    let discovery = discover_plain(root, MAX_FILE_BYTES)?;
    assert_eq!(
        flags(&discovery),
        [
            (".gitattributes", FileFlags::empty()),
            (".gitignore", FileFlags::empty()),
            ("a.tmp", FileFlags::empty()),
            ("b.tmp", FileFlags::empty()),
            ("x.c", FileFlags::GENERATED),
        ]
    );
    assert_eq!(discovery.problems, []);
    Ok(())
}

/// Folders deeper than the limit below the root are not entered and are reported; files in the
/// deepest folder within the limit are found.
#[test]
fn deep_folders_are_cut_off() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let at_depth = |depth: usize| vec!["d"; depth].join("/");
    let deepest = at_depth(cortex_index::MAX_FOLDER_DEPTH);
    let too_deep = at_depth(cortex_index::MAX_FOLDER_DEPTH + 1);
    write(root, &format!("{deepest}/deep.txt"), b"x\n")?;
    write(root, &format!("{too_deep}/deeper.txt"), b"x\n")?;
    let discovery = discover_plain(root, MAX_FILE_BYTES)?;
    let expected = format!("{deepest}/deep.txt");
    assert_eq!(paths(&discovery), [expected.as_str()]);
    assert_eq!(
        discovery.problems,
        [problem(&too_deep, ProblemKind::TooDeep)?]
    );
    Ok(())
}

/// A NUL byte makes a file binary only within the first 8 KiB: at byte 8191 it counts, at byte
/// 8192 it is never read.
#[test]
fn nul_bytes_count_only_in_the_first_8_kib() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let mut inside = vec![b'x'; 8192];
    inside[8191] = 0;
    let mut outside = vec![b'x'; 8193];
    outside[8192] = 0;
    write(root, "inside.dat", &inside)?;
    write(root, "outside.dat", &outside)?;
    let discovery = discover_plain(root, MAX_FILE_BYTES)?;
    assert_eq!(
        flags(&discovery),
        [
            ("inside.dat", FileFlags::BINARY),
            ("outside.dat", FileFlags::empty())
        ]
    );
    Ok(())
}

/// Lines of ignore and attribute files that cannot be used are reported by number, up to twenty a
/// file, and the rest of the file still applies; an attributes file too large to read is reported
/// and still recorded.
#[test]
fn rules_problems_are_reported() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(root, ".gitignore", b"a.rs\na[z-a]\n\xff\xfe.rs\nb.rs\n")?;
    write(
        root,
        ".gitattributes",
        b"*.c text\n!x.c linguist-generated\n",
    )?;
    write(root, "many/.gitignore", "a[z-a]\n".repeat(25).as_bytes())?;
    let mut big = b"*.c linguist-vendored\n".to_vec();
    big.resize(300, b'#');
    write(root, "big/.gitattributes", &big)?;
    for path in ["a.rs", "b.rs", "c.rs"] {
        write(root, path, b"x\n")?;
    }
    let discovery = discover_plain(root, 200)?;
    assert_eq!(
        flags(&discovery),
        [
            (".gitattributes", FileFlags::empty()),
            (".gitignore", FileFlags::empty()),
            ("big/.gitattributes", FileFlags::TOO_LARGE),
            ("c.rs", FileFlags::empty()),
            ("many/.gitignore", FileFlags::empty()),
        ]
    );
    let mut expected = vec![
        problem(".gitattributes", ProblemKind::BadRulesLine { line: 2 })?,
        problem(".gitignore", ProblemKind::BadRulesLine { line: 2 })?,
        problem(".gitignore", ProblemKind::BadRulesLine { line: 3 })?,
        problem("big/.gitattributes", ProblemKind::SkippedRulesFile)?,
    ];
    // Twenty of the twenty-five bad lines one by one, then the five left counted.
    for line in 1..=20 {
        expected.push(problem(
            "many/.gitignore",
            ProblemKind::BadRulesLine { line },
        )?);
    }
    expected.push(problem(
        "many/.gitignore",
        ProblemKind::MoreBadRulesLines { count: 5 },
    )?);
    assert_eq!(discovery.problems, expected);
    Ok(())
}

/// A missing global gitignore is no problem, as for git; an invalid extra pattern, named, or a
/// root that is not a folder stops the walk.
#[test]
fn bad_inputs_are_refused() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(root, "a.rs", b"fn a() {}\n")?;
    let missing = root.join("no-such-ignore");
    let discovery = discover(
        root,
        &DiscoverOptions {
            max_file_bytes: MAX_FILE_BYTES,
            extra_ignores: &[],
            global_gitignore: Some(&missing),
        },
    )?;
    assert_eq!(paths(&discovery), ["a.rs"]);
    assert_eq!(discovery.problems, []);

    let extra = vec!["*.tmp".to_owned(), "a[z-a]".to_owned()];
    let error = discover(
        root,
        &DiscoverOptions {
            max_file_bytes: MAX_FILE_BYTES,
            extra_ignores: &extra,
            global_gitignore: None,
        },
    )
    .err();
    assert!(
        matches!(&error, Some(DiscoverError::ExtraIgnore { pattern, .. }) if pattern == "a[z-a]"),
        "{error:?}"
    );
    let error = discover_plain(&root.join("a.rs"), MAX_FILE_BYTES).err();
    assert!(
        matches!(error, Some(DiscoverError::Root { .. })),
        "{error:?}"
    );
    Ok(())
}

/// Unix only: names that are not valid UTF-8 or hold a backslash, unreadable folders, symbolic
/// links and named pipes can only be made there. Bad names and the unreadable folder are
/// reported. Links are never followed, so a link loop does not trap the walk; a `.gitignore` that
/// links outside the repository and a `.cortexignore` that is a pipe are reported, never read,
/// and do not block the walk.
#[cfg(unix)]
#[test]
fn unix_only_problems_are_reported() -> TestResult {
    use std::ffi::OsStr;
    use std::os::unix::ffi::OsStrExt;
    use std::os::unix::fs::{PermissionsExt, symlink};
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let elsewhere = tempfile::tempdir()?;
    fs::write(elsewhere.path().join("ignore"), b"src/\n")?;
    write(root, "src/main.rs", b"fn main() {}\n")?;
    write(root, "bad\\name.rs", b"x\n")?;
    fs::write(root.join(OsStr::from_bytes(b"caf\xe9.rs")), b"x\n")?;
    write(root, "locked/a.rs", b"x\n")?;
    fs::set_permissions(root.join("locked"), fs::Permissions::from_mode(0o000))?;
    symlink(root.join("src/main.rs"), root.join("link.rs"))?;
    symlink(root, root.join("loop"))?;
    symlink(elsewhere.path().join("ignore"), root.join(".gitignore"))?;
    let status = std::process::Command::new("mkfifo")
        .arg(root.join(".cortexignore"))
        .status()?;
    assert!(status.success());
    let discovery = discover_plain(root, MAX_FILE_BYTES);
    fs::set_permissions(root.join("locked"), fs::Permissions::from_mode(0o700))?;
    let discovery = discovery?;
    assert_eq!(paths(&discovery), ["src/main.rs"]);
    let unstorable = Problem {
        path: None,
        kind: ProblemKind::UnstorableName,
    };
    assert_eq!(
        discovery.problems,
        [
            unstorable.clone(),
            unstorable,
            problem(".cortexignore", ProblemKind::SkippedRulesFile)?,
            problem(".gitignore", ProblemKind::SkippedRulesFile)?,
            problem("locked", ProblemKind::Unreadable)?,
        ]
    );
    // link.rs, loop, .gitignore and .cortexignore.
    assert_eq!(discovery.skipped_entries, 4);
    Ok(())
}
