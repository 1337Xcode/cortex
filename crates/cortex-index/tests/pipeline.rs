//! A full index of small repositories: what is written for each kind of file, the folders that
//! hold them, how a second index follows the changes, which stored files a later index removes or
//! keeps, that the number of threads changes nothing stored, and what becomes of a file that takes
//! too long to parse.

mod common;

use std::collections::BTreeMap;
use std::fs::File;
use std::path::Path;
use std::time::{Duration, UNIX_EPOCH};

use common::{NOW_MS, TestResult, index, lock_out, write};
use cortex_core::{
    ContentHash, EdgeType, FileFlags, Language, RepoPath, Resolution, ScaleMode, SymbolKind,
};
use cortex_index::{
    FileProblem, IndexReport, LeftOut, Problem, ProblemKind, RepoSize, ScipOutcome,
};
use cortex_store::{FileRow, NodeId, Reader, RefRow, SymbolRow};

/// A time limit no test file comes near, even in a debug build.
const GENEROUS: Duration = Duration::from_secs(60);

/// The size limit for the fixture, which its `big.py` passes.
const SMALL_LIMIT: u64 = 1000;

/// The default size limit, 1 MiB.
const DEFAULT_LIMIT: u64 = 1_048_576;

/// The modification time [`write_dated`] gives a file: 1,700,000,000 seconds after the Unix epoch.
const MTIME_SECONDS: u64 = 1_700_000_000;

/// [`MTIME_SECONDS`] in nanoseconds, as the store records it.
const MTIME_NS: i64 = 1_700_000_000_000_000_000;

/// The Python module of the fixture: `total` on lines 1-2 calls `sum` on line 2; the class `Order`
/// on lines 5-7 holds the method `place` on lines 6-7, which calls `total` on line 7.
const ORDERS_PY: &str = "def total(items):\n    return sum(items)\n\n\nclass Order:\n    def place(self):\n        return total([])\n";

/// One file of each kind the index treats apart, with its contents.
const FIXTURE: [(&str, &[u8]); 8] = [
    ("src/shop/orders.py", ORDERS_PY.as_bytes()),
    ("README.md", b"# Shop\n\nText.\n"),
    ("vendor/lib.js", b"function vendored() {}\n"),
    ("gen/types.rs", b"// @generated by a tool\npub struct T;\n"),
    (".env", b"TOKEN=x\n"),
    ("big.py", &[b'#'; 2000]),
    ("data.bin", b"\x00\x01\x02binary"),
    ("notes.txt", b"one\ntwo"),
];

/// What the store holds for one file.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Stored {
    /// Its language.
    language: Option<Language>,
    /// Its flags.
    flags: FileFlags,
    /// Its size.
    size_bytes: u64,
    /// Its modification time.
    mtime_ns: i64,
    /// How many lines it has.
    line_count: Option<u64>,
    /// The hash of its contents.
    content_hash: Option<ContentHash>,
    /// Kind, qualified name, first and last line of each definition, in order.
    symbols: Vec<(SymbolKind, String, u32, u32)>,
    /// Name, line, and the qualified name of the definition around it, of each reference.
    refs: Vec<(String, u32, Option<String>)>,
}

/// Every row stored for one file, with the nodes of the file and of its symbols.
#[derive(Debug, PartialEq)]
struct Rows {
    /// The file's row.
    file: FileRow,
    /// The file's node.
    node: Option<NodeId>,
    /// Each symbol's row and node.
    symbols: Vec<(SymbolRow, Option<NodeId>)>,
    /// Each reference's row.
    refs: Vec<RefRow>,
}

/// Writes `bytes` to `path` under `root`, creating folders as needed, and gives the file the
/// modification time [`MTIME_SECONDS`].
fn write_dated(root: &Path, path: &str, bytes: &[u8]) -> TestResult {
    write(root, path, bytes)?;
    let modified = UNIX_EPOCH + Duration::from_secs(MTIME_SECONDS);
    File::options()
        .write(true)
        .open(root.join(path))?
        .set_modified(modified)?;
    Ok(())
}

/// Writes the fixture under `root`.
fn write_fixture(root: &Path) -> TestResult {
    for (path, bytes) in FIXTURE {
        write_dated(root, path, bytes)?;
    }
    Ok(())
}

/// The contents of the fixture's file at `path`.
fn fixture(path: &str) -> TestResult<&'static [u8]> {
    let found = FIXTURE.iter().find(|(name, _)| *name == path);
    Ok(found.map(|(_, bytes)| *bytes).ok_or("not in the fixture")?)
}

/// A reader of the store of the repository at `root`.
fn reader(root: &Path) -> TestResult<Reader> {
    Ok(Reader::open(&root.join(".cortex"), 0)?)
}

/// What the store of the repository at `root` holds for the file at `path`; `None` when it holds
/// nothing.
fn stored(root: &Path, path: &str) -> TestResult<Option<Stored>> {
    let reader = reader(root)?;
    let queries = reader.queries();
    let Some(row) = queries.file(&RepoPath::new(path)?)? else {
        return Ok(None);
    };
    assert_eq!(row.file.indexed_at_ms, NOW_MS, "{path}");
    let symbols = queries.symbols_in_file(row.id)?;
    let name_of = |id| {
        symbols
            .iter()
            .find(|symbol| symbol.id == id)
            .map(|symbol| symbol.qual_name.as_str().to_owned())
    };
    let refs = queries
        .refs_in_file(row.id)?
        .into_iter()
        .map(|reference| {
            let around = reference.symbol.and_then(name_of);
            (
                reference.dst_name.as_str().to_owned(),
                reference.line,
                around,
            )
        })
        .collect();
    let file = row.file;
    Ok(Some(Stored {
        language: file.language,
        flags: file.flags,
        size_bytes: file.size_bytes,
        mtime_ns: file.mtime_ns,
        line_count: file.line_count,
        content_hash: file.content_hash,
        symbols: symbols
            .iter()
            .map(|symbol| {
                let name = symbol.qual_name.as_str().to_owned();
                (symbol.kind, name, symbol.start_line, symbol.end_line)
            })
            .collect(),
        refs,
    }))
}

/// A dated file the index read without parsing it: `bytes`, its contents, give its size and hash.
fn unparsed(
    language: Option<Language>,
    flags: FileFlags,
    line_count: u64,
    bytes: &[u8],
) -> TestResult<Stored> {
    Ok(Stored {
        language,
        flags,
        size_bytes: u64::try_from(bytes.len())?,
        mtime_ns: MTIME_NS,
        line_count: Some(line_count),
        content_hash: Some(ContentHash::of(bytes)),
        symbols: Vec::new(),
        refs: Vec::new(),
    })
}

/// A dated file the index did not read, as the walk found it.
fn unread(language: Option<Language>, flags: FileFlags, size_bytes: u64) -> Stored {
    Stored {
        language,
        flags,
        size_bytes,
        mtime_ns: MTIME_NS,
        line_count: None,
        content_hash: None,
        symbols: Vec::new(),
        refs: Vec::new(),
    }
}

/// The ids of the symbols stored for the file at `path`, in order.
fn symbol_ids(root: &Path, path: &str) -> TestResult<Vec<i64>> {
    let reader = reader(root)?;
    let queries = reader.queries();
    let row = queries
        .file(&RepoPath::new(path)?)?
        .ok_or("file not stored")?;
    let symbols = queries.symbols_in_file(row.id)?;
    Ok(symbols.iter().map(|symbol| symbol.id.get()).collect())
}

/// The paths of every file stored for the repository at `root`, in order.
fn stored_paths(root: &Path) -> TestResult<Vec<String>> {
    let paths = reader(root)?.queries().file_paths()?;
    Ok(paths.iter().map(|path| path.as_str().to_owned()).collect())
}

/// Each folder node stored for the repository at `root`, by path, with the paths of the files its
/// containment edges reach. Every edge from a folder is checked to be an undirected containment
/// edge of full strength, supported by one observation.
fn folders(root: &Path) -> TestResult<Vec<(String, NodeId, Vec<String>)>> {
    let reader = reader(root)?;
    let queries = reader.queries();
    let files: BTreeMap<NodeId, String> = queries
        .file_nodes()?
        .into_iter()
        .map(|(path, node)| (node, path.as_str().to_owned()))
        .collect();
    let mut folders = Vec::new();
    for (path, node) in queries.folder_nodes()? {
        let mut held = Vec::new();
        for row in queries.edges_from(node)? {
            let edge = row.edge;
            assert_eq!(row.edge_type, EdgeType::Containment, "{path:?}");
            assert!(edge.weight.total_cmp(&1.0).is_eq(), "{path:?}");
            assert_eq!((edge.count, edge.last_seq, edge.is_directed), (1, 0, false));
            held.push(files.get(&edge.dst).ok_or("an edge to no file")?.clone());
        }
        held.sort();
        folders.push((path.as_str().to_owned(), node, held));
    }
    Ok(folders)
}

/// One reference as resolution left it: its name, its line, the resolution, path and qualified name
/// of the definition it is tied to, and its stored confidence as text.
type Use = (String, u32, Option<(Resolution, String, String)>, String);

/// The references stored for the file at `path` of the repository at `root`, in order, each as
/// resolution left it.
fn resolutions(root: &Path, path: &str) -> TestResult<Vec<Use>> {
    let reader = reader(root)?;
    let queries = reader.queries();
    let mut definitions = BTreeMap::new();
    for file_path in queries.file_paths()? {
        let file = queries.file(&file_path)?.ok_or("listed file missing")?;
        for symbol in queries.symbols_in_file(file.id)? {
            let name = symbol.qual_name.as_str().to_owned();
            definitions.insert(symbol.id, (file_path.as_str().to_owned(), name));
        }
    }
    let file = queries
        .file(&RepoPath::new(path)?)?
        .ok_or("file not stored")?;
    let mut uses = Vec::new();
    for reference in queries.refs_in_file(file.id)? {
        let target = match reference.target {
            Some(target) => {
                let (file, name) = definitions
                    .get(&target.symbol)
                    .ok_or("a target that is not stored")?;
                Some((target.resolution, file.clone(), name.clone()))
            }
            None => None,
        };
        let name = reference.dst_name.as_str().to_owned();
        uses.push((
            name,
            reference.line,
            target,
            reference.confidence.to_string(),
        ));
    }
    Ok(uses)
}

/// Every row stored for the repository at `root`, file by file in path order.
fn dump(root: &Path) -> TestResult<Vec<Rows>> {
    let reader = reader(root)?;
    let queries = reader.queries();
    let mut dump = Vec::new();
    for path in queries.file_paths()? {
        let file = queries.file(&path)?.ok_or("listed file missing")?;
        let mut symbols = Vec::new();
        for symbol in queries.symbols_in_file(file.id)? {
            let node = queries.symbol_node(symbol.id)?;
            symbols.push((symbol, node));
        }
        dump.push(Rows {
            node: queries.file_node(file.id)?,
            refs: queries.refs_in_file(file.id)?,
            file,
            symbols,
        });
    }
    Ok(dump)
}

/// Every file is written as far as its kind allows: source Cortex parses with its definitions and
/// references; generated, vendored and other text with its size, lines and hash; a file that may
/// hold secrets, one over the size limit and a binary file as the walk found them, unread.
#[test]
fn every_file_is_written_as_its_kind_allows() -> TestResult {
    let repo = tempfile::tempdir()?;
    write_fixture(repo.path())?;
    let report = index(repo.path(), 2, GENEROUS, SMALL_LIMIT)?;
    let expected = IndexReport {
        files: 8,
        parsed: 2,
        unchanged: 0,
        removed: 0,
        walk_problems: Vec::new(),
        problems: Vec::new(),
        left_out: Vec::new(),
        changed_symbols: Vec::new(),
        scip: ScipOutcome::Absent,
        // Source: orders.py (7 lines) and README.md (3); the others are vendored, generated,
        // secret, too large, binary or in no language.
        size: RepoSize {
            source_files: 2,
            lines: 10,
        },
        mode: ScaleMode::Tiny,
    };
    assert_eq!(report, expected);
    let parsed = FileFlags::PARSED;
    let cases = [
        (".env", unread(None, FileFlags::SECRET_PATTERN, 8)),
        (
            "README.md",
            Stored {
                symbols: vec![(SymbolKind::Module, "Shop".to_owned(), 1, 1)],
                ..unparsed(Some(Language::Markdown), parsed, 3, fixture("README.md")?)?
            },
        ),
        (
            "big.py",
            unread(Some(Language::Python), FileFlags::TOO_LARGE, 2000),
        ),
        ("data.bin", unread(None, FileFlags::BINARY, 9)),
        (
            "gen/types.rs",
            unparsed(
                Some(Language::Rust),
                FileFlags::GENERATED,
                2,
                fixture("gen/types.rs")?,
            )?,
        ),
        (
            "notes.txt",
            unparsed(None, FileFlags::empty(), 2, fixture("notes.txt")?)?,
        ),
        (
            "src/shop/orders.py",
            Stored {
                symbols: vec![
                    (SymbolKind::Function, "total".to_owned(), 1, 2),
                    (SymbolKind::Class, "Order".to_owned(), 5, 7),
                    (SymbolKind::Method, "Order.place".to_owned(), 6, 7),
                ],
                refs: vec![
                    ("sum".to_owned(), 2, Some("total".to_owned())),
                    ("total".to_owned(), 7, Some("Order.place".to_owned())),
                ],
                ..unparsed(Some(Language::Python), parsed, 7, ORDERS_PY.as_bytes())?
            },
        ),
        (
            "vendor/lib.js",
            unparsed(
                Some(Language::JavaScript),
                FileFlags::VENDORED,
                1,
                fixture("vendor/lib.js")?,
            )?,
        ),
    ];
    for (path, expected) in cases {
        assert_eq!(stored(repo.path(), path)?, Some(expected), "{path}");
    }
    Ok(())
}

/// Every folder that holds files gets a node, joined to each of its files; `src`, which holds only
/// the folder `shop`, gets none. On a second index a folder whose files are all gone loses its
/// node, and the others keep theirs, with edges to the files they hold now: the root loses one
/// file and gains another, `src/shop` gains one.
#[test]
fn folders_hold_their_files() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write_fixture(root)?;
    index(root, 2, GENEROUS, SMALL_LIMIT)?;
    let before = folders(root)?;
    let expected = [
        (
            "",
            vec![".env", "README.md", "big.py", "data.bin", "notes.txt"],
        ),
        ("gen", vec!["gen/types.rs"]),
        ("src/shop", vec!["src/shop/orders.py"]),
        ("vendor", vec!["vendor/lib.js"]),
    ];
    assert_eq!(held(&before), expected);
    // Nodes: 8 files, 4 symbols (total, Order, Order.place, Shop) and 4 folders. Edges: one
    // containment edge per file, and one structural edge from `Order.place` to the `total` it
    // calls in its own file.
    let counts = reader(root)?.queries().counts()?;
    assert_eq!((counts.nodes, counts.edges), (16, 9));

    std::fs::remove_file(root.join("vendor/lib.js"))?;
    std::fs::remove_file(root.join("notes.txt"))?;
    write(root, "zeta.txt", b"z\n")?;
    write(root, "src/shop/new.py", b"def fresh():\n    pass\n")?;
    index(root, 2, GENEROUS, SMALL_LIMIT)?;
    let after = folders(root)?;
    let expected = [
        (
            "",
            vec![".env", "README.md", "big.py", "data.bin", "zeta.txt"],
        ),
        ("gen", vec!["gen/types.rs"]),
        ("src/shop", vec!["src/shop/new.py", "src/shop/orders.py"]),
    ];
    assert_eq!(held(&after), expected);
    let ids = |folders: &[(String, NodeId, Vec<String>)]| -> Vec<(String, NodeId)> {
        folders
            .iter()
            .filter(|(path, _, _)| path != "vendor")
            .map(|(path, node, _)| (path.clone(), *node))
            .collect()
    };
    assert_eq!(ids(&after), ids(&before));
    Ok(())
}

/// The folders of `folders` with the files each holds, without their nodes.
fn held(folders: &[(String, NodeId, Vec<String>)]) -> Vec<(&str, Vec<&str>)> {
    folders
        .iter()
        .map(|(path, _, files)| (path.as_str(), files.iter().map(String::as_str).collect()))
        .collect()
}

/// A reference is tied to the one definition with its name in its own file (confidence 0.6), or
/// else to the one definition with its name among files of its language family (0.3), or to
/// nothing. `local` is defined in `a.py` and `b.py`, so a call in `a.py` takes its own; `twice`
/// is defined in two Python files and `dup` twice in one, so calls to them stay loose; `render`
/// is defined only in TypeScript, which a JavaScript call reaches and a Python call does not; a
/// C++ call reaches a C function and a Kotlin call a Java method, and Java's `twice` is unique in
/// its family whatever Python defines. On a second index that cannot read `a.py`, its kept
/// references are resolved again: a second `shared` makes theirs ambiguous.
#[test]
fn references_resolve_by_file_then_by_family() -> TestResult {
    /// A target as the test writes it: resolution, file, qualified name, confidence as text.
    type Tie<'a> = (Resolution, &'a str, &'a str, &'a str);
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let a = "def helper():\n    pass\n\n\ndef local():\n    pass\n\n\ndef run():\n    helper()\n    local()\n    shared()\n    twice()\n    render()\n    dup()\n";
    write(root, "a.py", a.as_bytes())?;
    let b = "def shared():\n    pass\n\n\ndef twice():\n    pass\n\n\ndef local():\n    pass\n";
    write(root, "b.py", b.as_bytes())?;
    write(root, "c.py", b"def twice():\n    pass\n")?;
    let d = "def dup():\n    pass\n\n\ndef dup():\n    pass\n\n\ndup()\n";
    write(root, "d.py", d.as_bytes())?;
    write(root, "web/app.ts", b"export function render() {}\n")?;
    write(root, "web/use.js", b"render();\nhelper();\n")?;
    write(
        root,
        "native/lib.c",
        b"int add(int a, int b) { return a + b; }\n",
    )?;
    write(
        root,
        "native/main.cpp",
        b"int main() { return add(1, 2); }\n",
    )?;
    let util = "class Util {\n    static int twice(int x) {\n        return 2 * x;\n    }\n}\n";
    write(root, "jvm/Util.java", util.as_bytes())?;
    write(root, "jvm/main.kt", b"fun main() {\n    twice(2)\n}\n")?;
    index(root, 2, GENEROUS, DEFAULT_LIMIT)?;
    // The confidences the two rules give, 0.6 and 0.3, and 0 for none, as the store reads them.
    let tied = |name: &str, line, (resolution, file, qual_name, confidence): Tie<'_>| -> Use {
        let target = Some((resolution, file.to_owned(), qual_name.to_owned()));
        (name.to_owned(), line, target, confidence.to_owned())
    };
    let loose = |name: &str, line| -> Use { (name.to_owned(), line, None, "0".to_owned()) };
    let same_file = |file, name| (Resolution::SameFile, file, name, "0.6");
    let name_only = |file, name| (Resolution::NameOnly, file, name, "0.3");
    assert_eq!(
        resolutions(root, "a.py")?,
        [
            tied("helper", 10, same_file("a.py", "helper")),
            tied("local", 11, same_file("a.py", "local")),
            tied("shared", 12, name_only("b.py", "shared")),
            loose("twice", 13),
            loose("render", 14),
            loose("dup", 15),
        ]
    );
    assert_eq!(resolutions(root, "d.py")?, [loose("dup", 9)]);
    let from_js = [
        tied("render", 1, name_only("web/app.ts", "render")),
        loose("helper", 2),
    ];
    assert_eq!(resolutions(root, "web/use.js")?, from_js);
    assert_eq!(
        resolutions(root, "native/main.cpp")?,
        [tied("add", 1, name_only("native/lib.c", "add"))]
    );
    assert_eq!(
        resolutions(root, "jvm/main.kt")?,
        [tied("twice", 2, name_only("jvm/Util.java", "Util.twice"))]
    );

    write(root, "e.py", b"def shared():\n    pass\n")?;
    let report = {
        let _locked = lock_out(&root.join("a.py"))?;
        index(root, 2, GENEROUS, DEFAULT_LIMIT)?
    };
    assert_eq!(report.walk_problems.len(), 1, "{report:?}");
    assert_eq!(
        resolutions(root, "a.py")?,
        [
            tied("helper", 10, same_file("a.py", "helper")),
            tied("local", 11, same_file("a.py", "local")),
            loose("shared", 12),
            loose("twice", 13),
            loose("render", 14),
            loose("dup", 15),
        ]
    );
    assert_eq!(resolutions(root, "web/use.js")?, from_js);
    Ok(())
}

/// A file whose queries found a name it could not keep is written with the rest, and the report
/// says how many of each kind it left out: here a function whose name passes 256 bytes.
#[test]
fn names_left_out_are_reported() -> TestResult {
    let repo = tempfile::tempdir()?;
    let source = format!(
        "def {}():\n    pass\n\n\ndef kept():\n    pass\n",
        "f".repeat(300)
    );
    write(repo.path(), "long.py", source.as_bytes())?;
    let report = index(repo.path(), 1, GENEROUS, DEFAULT_LIMIT)?;
    let left_out = LeftOut {
        definitions: 1,
        references: 0,
        imports: 0,
    };
    assert_eq!(report.left_out, [(RepoPath::new("long.py")?, left_out)]);
    let stored = stored(repo.path(), "long.py")?.ok_or("long.py not stored")?;
    assert_eq!(
        stored.symbols,
        [(SymbolKind::Function, "kept".to_owned(), 5, 6)]
    );
    Ok(())
}

/// A second index follows the changes: a file the walk no longer finds is removed, a new one is
/// added, and a changed one rewritten, the symbols it still defines keeping their ids. A file the
/// walk cannot read is reported and keeps what was stored for it.
#[test]
fn a_second_index_follows_the_changes() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write_fixture(root)?;
    index(root, 2, GENEROUS, SMALL_LIMIT)?;
    let readme = stored(root, "README.md")?;
    let before = symbol_ids(root, "src/shop/orders.py")?;
    std::fs::remove_file(root.join("notes.txt"))?;
    let changed = format!("{ORDERS_PY}\n\ndef extra():\n    pass\n");
    write(root, "src/shop/orders.py", changed.as_bytes())?;
    write(root, "src/shop/new.py", b"def fresh():\n    pass\n")?;
    let report = {
        let _locked = lock_out(&root.join("README.md"))?;
        index(root, 2, GENEROUS, SMALL_LIMIT)?
    };
    let expected = IndexReport {
        // Written: orders.py, changed, and new.py; kept as they were: big.py, data.bin, .env,
        // gen/types.rs and vendor/lib.js. README.md the walk could not read, notes.txt is gone.
        files: 2,
        parsed: 2,
        unchanged: 5,
        removed: 1,
        walk_problems: vec![Problem {
            path: Some(RepoPath::new("README.md")?),
            kind: ProblemKind::Unreadable,
        }],
        problems: Vec::new(),
        left_out: Vec::new(),
        changed_symbols: Vec::new(),
        scip: ScipOutcome::Absent,
        // Source: orders.py (7 lines and 4 more), new.py (2) and README.md, kept with its 3.
        size: RepoSize {
            source_files: 3,
            lines: 16,
        },
        mode: ScaleMode::Tiny,
    };
    assert_eq!(report, expected);
    assert_eq!(stored(root, "notes.txt")?, None);
    assert_eq!(stored(root, "README.md")?, readme);
    let orders = stored(root, "src/shop/orders.py")?.ok_or("no orders.py")?;
    assert_eq!(
        orders.symbols,
        [
            (SymbolKind::Function, "total".to_owned(), 1, 2),
            (SymbolKind::Class, "Order".to_owned(), 5, 7),
            (SymbolKind::Method, "Order.place".to_owned(), 6, 7),
            (SymbolKind::Function, "extra".to_owned(), 10, 11),
        ]
    );
    let after = symbol_ids(root, "src/shop/orders.py")?;
    assert_eq!(after.get(..3), Some(&before[..]));
    assert!(after.get(3).is_some_and(|id| !before.contains(id)));
    let fresh = stored(root, "src/shop/new.py")?.ok_or("no new.py")?;
    assert_eq!(
        fresh.symbols,
        [(SymbolKind::Function, "fresh".to_owned(), 1, 2)]
    );
    Ok(())
}

/// More files gone than one batch removes are all removed: 300 of them, in two batches;
/// `keep.txt`, unchanged, is kept as it was.
#[test]
fn every_file_gone_is_removed() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    for number in 0..300 {
        write(root, &format!("parts/part{number:03}.py"), b"x = 1\n")?;
    }
    write(root, "keep.txt", b"kept\n")?;
    index(root, 4, GENEROUS, DEFAULT_LIMIT)?;
    assert_eq!(stored_paths(root)?.len(), 301);
    for number in 0..300 {
        std::fs::remove_file(root.join(format!("parts/part{number:03}.py")))?;
    }
    let report = index(root, 4, GENEROUS, DEFAULT_LIMIT)?;
    assert_eq!(
        (report.files, report.unchanged, report.removed),
        (0, 1, 300)
    );
    assert_eq!(stored_paths(root)?, ["keep.txt"]);
    Ok(())
}

/// Files in a folder the walk cannot list stay as they were stored, and the folder is reported.
/// Unix only: a test there can take a folder's permissions away from its owner, which Windows
/// does not offer without rewriting the folder's access list.
#[cfg(unix)]
#[test]
fn files_in_a_folder_the_walk_cannot_list_are_kept() -> TestResult {
    use std::os::unix::fs::PermissionsExt;
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    write(root, "locked/a.py", b"def a():\n    pass\n")?;
    write(root, "open.txt", b"open\n")?;
    index(root, 2, GENEROUS, DEFAULT_LIMIT)?;
    let before = stored(root, "locked/a.py")?;
    std::fs::set_permissions(root.join("locked"), std::fs::Permissions::from_mode(0o000))?;
    let report = index(root, 2, GENEROUS, DEFAULT_LIMIT);
    std::fs::set_permissions(root.join("locked"), std::fs::Permissions::from_mode(0o700))?;
    let report = report?;
    assert_eq!((report.files, report.removed), (1, 0));
    let unlisted = Problem {
        path: Some(RepoPath::new("locked")?),
        kind: ProblemKind::Unreadable,
    };
    assert_eq!(report.walk_problems, [unlisted]);
    assert!(before.is_some());
    assert_eq!(stored(root, "locked/a.py")?, before);
    Ok(())
}

/// The number of threads changes nothing stored, row for row and node for node, folder nodes
/// included: each batch is written in path order however its threads finish. A slow file early in
/// the order lets the other threads run ahead of the one parsing it, and 309 files fill more than
/// one batch.
#[test]
fn threads_change_nothing_stored() -> TestResult {
    let mut dumps = Vec::new();
    for threads in [1, 4] {
        let repo = tempfile::tempdir()?;
        write_fixture(repo.path())?;
        let slow: String = (0..2000)
            .map(|number| format!("def slow{number}():\n    return {number}\n"))
            .collect();
        write_dated(repo.path(), "a_slow.py", slow.as_bytes())?;
        for number in 0..300 {
            let next = number + 1;
            let source = format!("def part{number}():\n    return part{next}()\n");
            let path = format!("parts/part{number:03}.py");
            write_dated(repo.path(), &path, source.as_bytes())?;
        }
        let report = index(repo.path(), threads, GENEROUS, DEFAULT_LIMIT)?;
        // The fixture's 8 files, of which orders.py, README.md and, under this limit, big.py are
        // parsed; a_slow.py; 300 parts.
        assert_eq!(
            (report.files, report.parsed),
            (309, 304),
            "{threads} threads"
        );
        dumps.push((dump(repo.path())?, folders(repo.path())?));
    }
    // Folders: the root (a_slow.py's too), parts, and the fixture's gen, src/shop and vendor.
    let sizes = dumps
        .first()
        .map(|(rows, folders)| (rows.len(), folders.len()));
    assert_eq!(sizes, Some((309, 5)));
    assert_eq!(dumps.first(), dumps.get(1));
    Ok(())
}

/// A file that takes longer to parse than allowed is reported. A new one is written as read,
/// defining nothing, and is not tried again until it changes; one stored as parsed keeps its rows
/// and ids. The file after it is still written. With no time at all, parsing stops at its first
/// look at the clock, which a file of 5,000 functions certainly reaches.
#[test]
fn a_file_out_of_time_is_reported_and_tried_again_when_it_changes() -> TestResult {
    let repo = tempfile::tempdir()?;
    let root = repo.path();
    let slow: String = (0..5000)
        .map(|number| format!("def f{number}():\n    pass\n"))
        .collect();
    write_dated(root, "slow.py", slow.as_bytes())?;
    write_dated(root, "z.txt", b"after\n")?;
    // slow.py is Python source of 5,000 functions of two lines each.
    let out_of_time = IndexReport {
        files: 2,
        parsed: 0,
        unchanged: 0,
        removed: 0,
        walk_problems: Vec::new(),
        problems: vec![(RepoPath::new("slow.py")?, FileProblem::TimedOut)],
        left_out: Vec::new(),
        changed_symbols: Vec::new(),
        scip: ScipOutcome::Absent,
        size: RepoSize {
            source_files: 1,
            lines: 10_000,
        },
        mode: ScaleMode::Tiny,
    };
    assert_eq!(index(root, 1, Duration::ZERO, DEFAULT_LIMIT)?, out_of_time);
    let read = unparsed(
        Some(Language::Python),
        FileFlags::empty(),
        10_000,
        slow.as_bytes(),
    )?;
    assert_eq!(stored(root, "slow.py")?, Some(read.clone()));
    assert_eq!(
        stored(root, "z.txt")?,
        Some(unparsed(None, FileFlags::empty(), 1, b"after\n")?)
    );
    // Unchanged, it is not tried again, whatever the time allowed.
    let unchanged = index(root, 1, GENEROUS, DEFAULT_LIMIT)?;
    assert_eq!((unchanged.files, unchanged.unchanged), (0, 2));
    assert_eq!(stored(root, "slow.py")?, Some(read));
    // One more function makes it changed: read and parsed again, now in time.
    let with_g = format!("{slow}def g():\n    pass\n");
    write_dated(root, "slow.py", with_g.as_bytes())?;
    index(root, 1, GENEROUS, DEFAULT_LIMIT)?;
    let parsed = stored(root, "slow.py")?.ok_or("no slow.py")?;
    assert_eq!(
        (parsed.flags, parsed.symbols.len()),
        (FileFlags::PARSED, 5001)
    );
    let ids = symbol_ids(root, "slow.py")?;
    // Changed again and out of time, it keeps its stored rows: 5,001 functions, 10,002 lines.
    write_dated(
        root,
        "slow.py",
        format!("{with_g}def h():\n    pass\n").as_bytes(),
    )?;
    let kept = IndexReport {
        files: 0,
        unchanged: 1,
        size: RepoSize {
            source_files: 1,
            lines: 10_002,
        },
        ..out_of_time
    };
    assert_eq!(index(root, 1, Duration::ZERO, DEFAULT_LIMIT)?, kept);
    assert_eq!(stored(root, "slow.py")?, Some(parsed));
    assert_eq!(symbol_ids(root, "slow.py")?, ids);
    Ok(())
}
