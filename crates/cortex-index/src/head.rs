//! What the first bytes of a file say about it: whether it is text, and whether a code generator
//! wrote it.

/// How many bytes from the start of a file are read. A NUL byte among them means the file is not
/// text; a generator's marker is looked for only among them.
pub const HEAD_BYTES: u64 = 8192;

/// How many lines at the start of a text file may carry a generator's marker. Generators write it
/// at the top, sometimes below a licence header of a dozen lines or so.
const MARKER_LINES: usize = 40;

/// Texts code generators write into the comments at the top of their output.
const GENERATOR_MARKERS: &[&[u8]] = &[b"@generated", b"DO NOT EDIT", b"Code generated"];

/// How comments start in the languages Cortex reads. A marker counts only in a line that starts
/// with one of these, so a file that merely mentions a marker in its code is not mistaken for
/// generated output.
const COMMENT_STARTS: &[&[u8]] = &[b"//", b"/*", b"*", b"#", b"--", b"<!--", b";", b"%"];

/// Bytes right after `#` that make the line code rather than a comment: a Rust attribute (`#[`)
/// or a shebang (`#!`).
const HASH_CODE_MARKS: &[u8] = b"[!";

/// C preprocessor directives: a `#` line whose first word is one of these is code.
const PREPROCESSOR_WORDS: &[&[u8]] = &[
    b"include", b"define", b"if", b"ifdef", b"ifndef", b"else", b"elif", b"endif", b"pragma",
    b"undef", b"error", b"import", b"line", b"warning",
];

/// The UTF-8 byte order mark some editors put before the first line.
const BYTE_ORDER_MARK: &[u8] = b"\xEF\xBB\xBF";

/// What the start of a file says.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Head {
    /// A NUL byte appears in the bytes judged.
    pub is_binary: bool,
    /// A comment near the top carries a code generator's marker.
    pub is_generated: bool,
}

/// Judges the first bytes of a file, at most [`HEAD_BYTES`] of them.
#[must_use]
pub fn judge(start: &[u8]) -> Head {
    let is_binary = start.contains(&0);
    let text = start.strip_prefix(BYTE_ORDER_MARK).unwrap_or(start);
    let is_generated = !is_binary
        && text
            .split(|byte| *byte == b'\n')
            .take(MARKER_LINES)
            .any(is_marker_comment);
    Head {
        is_binary,
        is_generated,
    }
}

/// Whether `line` is a comment carrying a generator's marker.
fn is_marker_comment(line: &[u8]) -> bool {
    let code = line.trim_ascii_start();
    let is_comment = COMMENT_STARTS.iter().any(|start| code.starts_with(start))
        && !code.strip_prefix(b"#").is_some_and(is_hash_code);
    is_comment
        && GENERATOR_MARKERS
            .iter()
            .any(|marker| code.windows(marker.len()).any(|window| window == *marker))
}

/// Whether a line starting with `#` and going on with `rest` is code: an attribute, a shebang or
/// a preprocessor directive written right after the `#` (`#if`, `#include`), whose word must end
/// where the directive's name ends. With a space after the `#` the line reads as a comment, as in
/// `# if you change this`, though C also allows `#  if`.
fn is_hash_code(rest: &[u8]) -> bool {
    if rest
        .first()
        .is_some_and(|byte| HASH_CODE_MARKS.contains(byte))
    {
        return true;
    }
    PREPROCESSOR_WORDS.iter().any(|directive| {
        rest.strip_prefix(*directive).is_some_and(|after| {
            after
                .first()
                .is_none_or(|byte| !byte.is_ascii_alphanumeric() && *byte != b'_')
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A NUL byte anywhere in the head makes the file binary, and a binary file is never judged
    /// generated.
    #[test]
    fn nul_bytes_mean_binary() {
        assert_eq!(
            judge(b"plain text\nmore text\n"),
            Head {
                is_binary: false,
                is_generated: false
            }
        );
        assert!(judge(b"PNG\0\x01\x02").is_binary);
        let binary_with_marker = judge(b"// @generated\n\0");
        assert!(binary_with_marker.is_binary);
        assert!(!binary_with_marker.is_generated);
    }

    /// Each marker counts in a comment line of any of the comment styles, also after a byte order
    /// mark.
    #[test]
    fn markers_in_comments_mean_generated() {
        for start in [
            "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n",
            "# @generated by a tool\nx = 1\n",
            "/* DO NOT EDIT */\n",
            " * @generated\n",
            "-- Code generated by sqlc\n",
            "<!-- DO NOT EDIT -->\n",
            "; @generated\n",
            "% DO NOT EDIT\n",
            "\u{feff}// Code generated by a tool. DO NOT EDIT.\n",
            "# imported from upstream; DO NOT EDIT\n",
            "# if you change this file: DO NOT EDIT\n",
            "#important: DO NOT EDIT\n",
        ] {
            assert!(judge(start.as_bytes()).is_generated, "{start}");
        }
    }

    /// A marker outside a comment, in a Rust attribute, a shebang or a preprocessor line, a comment
    /// without one, or a marker past the first 40 lines does not count.
    #[test]
    fn other_mentions_do_not_count() {
        for start in [
            "const MARKER: &str = \"DO NOT EDIT\";\n",
            "#[doc = \"DO NOT EDIT this by hand\"]\n",
            "#!/usr/bin/env tool --header @generated\n",
            "#include \"DO NOT EDIT.h\"\n",
            "#define BANNER \"Code generated\"\n",
            "#ifdef MARKER // DO NOT EDIT\n",
            "// written by hand\nfn main() {}\n",
        ] {
            assert!(!judge(start.as_bytes()).is_generated, "{start}");
        }
        let mut late = "// line\n".repeat(40);
        late.push_str("// Code generated by a tool\n");
        assert!(!judge(late.as_bytes()).is_generated);
        let mut in_time = "// line\n".repeat(39);
        in_time.push_str("// Code generated by a tool\n");
        assert!(judge(in_time.as_bytes()).is_generated);
    }
}
